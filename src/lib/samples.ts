export function buildSamples(now = Date.now()): Doc[] {
  const hour = 3600 * 1000
  const day = 24 * hour
  const make = (title: string, content: string, age: number, pinned = false): Doc => ({
    id: newId(),
    title,
    content,
    createdAt: now - age - 2 * hour,
    updatedAt: now - age,
    pinned,
  })

  return [
    make('欢迎使用 MarkPad', WELCOME, 12 * 60 * 1000, true),
    make('本周待办', TODO, 3 * hour, true),
    make('深度工作 · 读书笔记', BOOKNOTE, day + 5 * hour),
    make('Markdown 语法速查', CHEATSHEET, 3 * day),
    make('一些还没成形的想法', IDEAS, 9 * day),
  ]
}
